-- ============================================================================
--  raw.lua — сирі записи сигналу
--
--  Не розбирає сигнал, а зберігає його цілком — список тривалостей —
--  і відтворює як є, як магнітофонний запис. Підходить для будь-якої
--  техніки, навіть якщо її протокол невідомий: кондиціонери, приставки.
--
--  Мінус: це знімок одного натискання. У кондиціонера кожне натискання
--  несе весь стан (режим, температуру), тому запис кнопки "+" завжди
--  встановлюватиме ту саму температуру.
-- ============================================================================

local raw = {}

raw.name = "raw"
raw.carrier = 38000 -- майже вся побутова техніка на 38 кГц
raw.repeatable = false -- не повторювати при утриманні: кондиціонер
-- від повтору вмикався б і вимикався по черзі

-- --- Надсилання -------------------------------------------------------------
-- Код сирої команди — це вже готовий список тривалостей.

function raw.encode(address, code)
    return code
end

-- --- Вивчення ---------------------------------------------------------------
-- Приймає будь-що, схоже на пульт: досить довге і зі стартовим спалахом.
-- Тому в реєстрі протоколів raw має стояти останнім.

function raw.decode(edges)
    if #edges < 60 or edges[1] < 2000 then return nil end

    local list = {}
    for i, us in ipairs(edges) do
        list[i] = math.floor(us + 0.5) -- до цілих мікросекунд
    end

    return {address = 0, command = list, valid = true}
end

-- --- Рядок у файлі ----------------------------------------------------------
--     Увімк / вимк        raw 8759 4395 610 1617 ...

function raw.format(code)
    return "raw " .. table.concat(code, " ")
end

function raw.parse(line)
    local name, numbers = line:match("^(.-)%s+raw%s+([%d%s]+)$")
    if not name then return nil end

    local list = {}
    for n in numbers:gmatch("%d+") do
        list[#list + 1] = tonumber(n)
    end
    return name, list
end

-- Коротко для екрана — праворуч від назви команди
function raw.label(code)
    return "raw"
end

return raw
